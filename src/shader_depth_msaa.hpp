// The pass that turns the depth buffer into the full size linear depth texture
// that the fog, depth of field and soft particles all sample.
//
// The game's own shader reads depth with a plain 2D sample. Once the depth
// buffer is multisampled that sample has no meaning: a multisampled surface
// keeps its samples interleaved and cannot be addressed that way, so the values
// come back scrambled and every effect downstream inherits it, as bands across
// the screen.
// 
// Direct3D 11 quietly gives back something usable anyway, but Direct3D 12 does not.
//
// Reading it correctly means declaring the texture as multisampled and loading
// a single sample by integer pixel coordinate:
//
//   sample r0.x, v2.xyxx, t0.xyzw, s0   ->   ftoi  r0.xy, v0.xyxx
//                                            ldms  r0.x, r0.xyxx, t0.xyzw, l(0)
//
// The coordinate is what stops this being a patch. The original interpolates a
// texture coordinate, a load needs pixels, and the position input that already
// carries them is declared in the signature but never read, so reading it costs
// an input declaration and a convert that a 48 instruction shader has no room
// for. The whole shader is carried here instead.
//
// Sample 0 is enough. The result is one value per pixel whatever the sample
// count, which is what every reader of the linear depth texture expects.
//
// Only valid while the depth buffer is multisampled. With multisampling off the
// renderer builds a plain 2D view and this shader is wrong in the other
// direction, so it is only handed over when a sample count is set.
